        j, _ = self.make_judge([self.reply('{"verdict": "maybe", "reason": "?"}')])
        self.assertIn("neither pass nor fail", j.judge("docs-updated", {})["reason"])
        j, _ = self.make_judge([(200, json.dumps({"stop_reason": "refusal", "content": []}))])
        self.assertIn("refused", j.judge("docs-updated", {})["reason"])
        j, _ = self.make_judge([self.reply("Verdict follows: {\"verdict\":\"pass\",\"reason\":\"ok\"}")])
        self.assertEqual(j.judge("docs-updated", {})["verdict"], "pass")

