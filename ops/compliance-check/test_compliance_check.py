class MetricsTest(unittest.TestCase):
    """The nanoclaw_compliance measurement re-emits latest.json without re-deriving
    any rule, and a missing report is an error, not zero."""

    def setUp(self):
        self.root = tempfile.mkdtemp(prefix="compliance-metrics-test.")
        self.metrics = load_module(
            "nanoclaw_metrics_under_compliance_test",
            os.path.join(REPO, "ops", "metrics", "nanoclaw-metrics.py"),
            {"NANOCLAW_DIR": self.root},
        )

    def tearDown(self):
        shutil.rmtree(self.root, ignore_errors=True)

    def test_emits_per_rule_rates_and_totals(self):
        out_dir = os.path.join(self.root, "data", "shared", "compliance")
        os.makedirs(out_dir)
        doc = {
            "status": "findings", "complete": False, "exitCode": 1,
            "counts": {
                "ok": 1, "drift": 4, "unknown": 3, "findings": 119, "items": 248,
                "perRule": {
                    "pr-description": {"pass": 0, "fail": 22, "unknown": 0, "total": 22, "rate": 0.0},
                    "issue-wait": {"pass": 4, "fail": 34, "unknown": 0, "total": 38, "rate": 0.1053},
                    "discord-thread": {"pass": 0, "fail": 0, "unknown": 0, "total": 0, "rate": None},
                },
            },
            "judge": {"impl": "null"},
        }
        with open(os.path.join(out_dir, "latest.json"), "w") as fh:
            json.dump(doc, fh)
        self.metrics.collect_compliance()
        self.assertEqual(len(self.metrics._out), 1)
        line = self.metrics._out[0]
        self.assertTrue(line.startswith("nanoclaw_compliance,judge=null,status=findings "), line)
        for frag in ("findings=119i", "unknown=3i", "items=248i", "complete=false", "exit_code=1i",
                     "r_pr_description_pass=0i", "r_pr_description_total=22i", "r_pr_description_rate=0,",
                     "r_issue_wait_pass=4i", "r_issue_wait_rate=0.1053", "r_discord_thread_total=0i"):
            self.assertIn(frag, line)
        self.assertNotIn("r_discord_thread_rate", line)  # no items: no rate, rather than a fake zero

    def test_missing_report_is_an_error_not_zero(self):
        with self.assertRaises(OSError):
            self.metrics.collect_compliance()
        self.assertEqual(self.metrics._out, [])


