    def make_judge(self, replies, **kw):
        """A judge over a fake transport that pops one (status, body) per request."""
        calls = []

        def transport(url, headers, body, timeout):
            calls.append((url, headers, json.loads(body)))
            return replies.pop(0)

        j = self.mod.AnthropicMessagesJudge("https://proxy.example/anthropic", token="tok", transport=transport, sleep=lambda s: None, **kw)
        return j, calls

    @staticmethod
    def reply(text, status=200):
        return status, json.dumps({"content": [{"type": "text", "text": text}], "stop_reason": "end_turn"})

    def test_anthropic_judge_parses_verdict_and_sends_rubric(self):
        j, calls = self.make_judge([self.reply('{"verdict": "fail", "reason": "Comments narrate the code."}')])
        v = j.judge("comment-rationale", {"title": "t", "comments": "// adds one to x"})
        self.assertEqual(v, {"verdict": "fail", "reason": "Comments narrate the code."})
        url, headers, body = calls[0]
        self.assertEqual(url, "https://proxy.example/anthropic/v1/messages")
        self.assertEqual(headers["authorization"], "Bearer tok")
        self.assertEqual(body["model"], "claude-opus-5-5")
        self.assertIn("contract", body["system"])
        self.assertIn("adds one to x", body["messages"][0]["content"])

    def test_anthropic_judge_retries_then_gives_up_as_unknown(self):
        j, calls = self.make_judge([(429, "slow down"), self.reply('{"verdict":"pass","reason":"fine"}')])
        self.assertEqual(j.judge("docs-updated", {})["verdict"], "pass")
        self.assertEqual(len(calls), 2)
        j, calls = self.make_judge([(500, "x"), (502, "y"), (503, "z"), (500, "w")], retries=3)
        v = j.judge("docs-updated", {})
        self.assertEqual(v["verdict"], "unknown")
        self.assertIn("HTTP 500", v["reason"])
        self.assertEqual(len(calls), 4)
        j, calls = self.make_judge([(401, "bad key")])
        self.assertEqual(j.judge("docs-updated", {})["verdict"], "unknown")
        self.assertEqual(len(calls), 1)  # client errors are not retried
        self.assertEqual(j.describe()["transport_failures"], 1)

