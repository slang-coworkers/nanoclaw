    def test_collect_normalises_and_attributes(self):
        col = self.mod.collect(self.gh, FakeGitHub.REPO, SINCE)
        self.assertEqual(col["problems"], [])
        by_id = {it["id"]: it for it in col["items"]}
        self.assertEqual(by_id["slang#10"]["coworker"], "fixer")
        self.assertEqual(by_id["slang#20"]["coworker"], "triager")
        kinds = {}
        for it in col["items"]:
            kinds.setdefault(it["kind"], []).append(it["coworker"])
        self.assertEqual(sorted(kinds["review"]), ["reviewer"])  # the empty-body review is dropped
        self.assertEqual(sorted(kinds["review_comment"]), ["fixer", "reviewer"])
        self.assertEqual(kinds["issue_comment"].count("triager"), 6)
        self.assertEqual(kinds["issue_comment"].count("fixer"), 1)  # comment on the bot's own PR
        self.assertEqual(kinds["issue_comment"].count("reviewer"), 1)  # comment on a human PR
        self.assertNotIn("coderabbitai[bot]", json.dumps(col["items"]))
        self.assertIsNotNone(by_id["slang#10"]["files"])

