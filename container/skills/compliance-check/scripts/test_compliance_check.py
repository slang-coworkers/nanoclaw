        self.calls.append((path, dict(params or {})))
        if path in self.fail_paths:
            raise RuntimeError(f"HTTP 500 for {path}")
        r = self.REPO
        q = (params or {}).get("q", "")
        if path == "search/issues":
            if "is:pr author:" in q:
                return {"items": self.prs}
            if "is:issue author:" in q:
                return {"items": [self.issues[20]]}
