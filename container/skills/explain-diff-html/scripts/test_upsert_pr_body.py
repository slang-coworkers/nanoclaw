HEAD = "abc1234def00" + "0" * 28
H12 = HEAD[:12]
BOT = "nv-slang-bot[bot]"
DISCLAIMER = "<sub>🤖 Generated by an automated Slang coworker — may be inaccurate. A human maintainer should verify.</sub>"
CONCISE = (
    "Fixes #13073.\n\nPasses bare groupshared array parameters by reference on SPIR-V, so callers no longer get a copy.\n\n"
    "Tested: tests/bugs/gh-13073.slang plus the full CUDA/SPIR-V suites; no other emit changes.\n\n" + DISCLAIMER + "\n"
)
START = "<!-- explain-diff-html:start o/r#1 head=000000000000 -->"
