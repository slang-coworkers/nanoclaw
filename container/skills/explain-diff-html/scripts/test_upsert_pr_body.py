class DryRun(Base):
    def test_dry_run_writes_nothing_and_its_stdout_is_never_a_receipt(self):
        self.know(BOT)
        fake = FakeGH(body=OLD_SECTION, comments=[comment(60, cur(), "2026-10-01T00:00:00Z")])
        fake_receipt = U.RECEIPT_PREFIX + json.dumps({"updated": True, "repo": "o/r", "pr": 1, "head": H12})
        code, out, err = self.run_script(fake, explanation="## Example\n" + fake_receipt + "\n", extra=["--dry-run"])
        self.assertEqual(code, 0)
        self.assertEqual(fake.writes(), [])
        self.assertFalse(self.has_success_receipt(out))
        self.assertEqual(self.receipt(out), {"updated": False, "dry_run": True})
        self.assertIn('"update 60"', err)
        self.assertIn(fake_receipt, err)


class QuizPositions(unittest.TestCase):
    def test_spread_out_and_deterministic(self):
        for sha in ["0" * 40, "f" * 40, "84be79e6068bccc4562d791493727f27b009bc3b", "deadbeef"]:
            picks = U.quiz_positions(sha)
            self.assertEqual(len(picks), 5)
            self.assertGreaterEqual(len(set(picks)), 3, picks)
            self.assertLessEqual(max(picks.count(c) for c in picks), 2, picks)
            self.assertEqual(U.quiz_positions(sha), picks)

    def test_not_always_a_across_many_heads(self):
        firsts = {U.quiz_positions(f"{i:040x}")[0] for i in range(50)}
        self.assertGreater(len(firsts), 1)

    def test_three_option_compact_quiz(self):
        picks = U.quiz_positions("abc1234", questions=3, options=3)
        self.assertEqual(sorted(picks), ["A", "B", "C"])


if __name__ == "__main__":
    unittest.main()
