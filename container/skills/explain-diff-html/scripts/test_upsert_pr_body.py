import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import upsert_pr_body as U

HEAD = "abc1234def00" + "0" * 28
H12 = HEAD[:12]
BOT = "slang-coworkers[bot]"
DISCLAIMER = "<sub>🤖 Generated by an automated Slang coworker — may be inaccurate. A human maintainer should verify.</sub>"
CONCISE = (
    "Fixes #13073.\n\nPasses bare groupshared array parameters by reference on SPIR-V, so callers no longer get a copy.\n\n"
    "Tested: tests/bugs/gh-13073.slang plus the full CUDA/SPIR-V suites; no other emit changes.\n\n" + DISCLAIMER + "\n"
)
OLD_SECTION = (
    "<!-- explain-diff-html:start o/r#1 head=000000000000 -->\n\n## 📖 Explanation\n\nA very long explanation.\n\n"
    "<!-- explain-diff-html:end -->"
)


def cur(head="000000000000", ref="o/r#1", text="old"):
    return f"<!-- explain-diff-html:comment {ref} head={head} -->\n\n{text}"


class FakeGH:
    """Records gh calls; serves a PR, its comments, and accepts edits."""

    def __init__(self, body="", comments=None, live=HEAD, author=BOT, me="", fail_patch=(), on_post=None):
        self.body, self.live, self.author, self.me = body, live, author, me
        self.comments = {c["id"]: dict(c) for c in (comments or [])}
        self.fail_patch = set(fail_patch)
        self.on_post = on_post
        self.calls, self.next_id = [], 900

    @staticmethod
    def _body(args):
        for i, x in enumerate(args):
            if x == "-F" and args[i + 1].startswith("body=@"):
                with open(args[i + 1][6:], encoding="utf-8") as f:
                    return f.read()
        return None

    def writes(self):
        return [c for c in self.calls if "-X" in c]

    def __call__(self, args):
        self.calls.append(args)
        if args[:2] == ["api", "user"]:
            return (True, self.me + "\n") if self.me else (False, "HTTP 403: Resource not accessible by integration")
        path = next(x for x in args if x.startswith("repos/"))
        method = args[args.index("-X") + 1] if "-X" in args else "GET"
        if method == "GET" and path.endswith("/comments"):
            ordered = sorted(self.comments.values(), key=lambda c: (c["created_at"], c["id"]))
            return True, "\n".join(json.dumps(c) for c in ordered)
        if method == "GET" and "/pulls/" in path:
            return True, json.dumps({"body": self.body, "head": self.live, "author": self.author})
        if method == "PATCH" and "/issues/comments/" in path:
            cid = int(path.rsplit("/", 1)[1])
            if cid in self.fail_patch:
                return False, "HTTP 502: Bad Gateway"
            self.comments[cid]["body"] = self._body(args)
            return True, ""
        if method == "POST" and path.endswith("/comments"):
            self.next_id += 1
            cid = self.next_id
            self.comments[cid] = comment(cid, self._body(args), "2026-10-05T00:00:00Z", login=BOT, kind="Bot")
            if self.on_post:
                self.on_post(self)
            return True, json.dumps({"id": cid, "login": BOT})
        if method == "PATCH" and "/pulls/" in path:
            self.body = self._body(args)
            return True, ""
        raise AssertionError(f"unexpected gh call {args}")


def comment(cid, body, at, login=BOT, kind="Bot"):
    return {"id": cid, "created_at": at, "html_url": f"https://github.com/o/r/pull/1#issuecomment-{cid}",
            "body": body, "login": login, "type": kind}


def human(cid, body, at, login="maintainer"):
    return comment(cid, body, at, login=login, kind="User")


class Run(unittest.TestCase):
    def run_script(self, fake, explanation="## 📖 Explanation\n\n### Background\nx\n", extra=()):
        with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False, encoding="utf-8") as f:
            f.write(explanation)
        old = U.gh_try
        U.gh_try = fake
        out, err = io.StringIO(), io.StringIO()
        try:
            with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
                code = U.main(["--repo", "o/r", "--pr", "1", "--head", H12, "--explanation", f.name, *extra])
        finally:
            U.gh_try = old
            os.unlink(f.name)
        return code, out.getvalue(), err.getvalue()

    @staticmethod
    def receipt(out):
        return json.loads(out.strip().splitlines()[-1])

    @staticmethod
    def has_receipt(out):
        return any(line.startswith("{") and '"updated": true' in line for line in out.splitlines())

    # --- creating and updating -------------------------------------------------

    def test_creates_the_comment_when_none_exists(self):
        fake = FakeGH(body=CONCISE)
        code, out, _ = self.run_script(fake)
        self.assertEqual(code, 0)
        r = self.receipt(out)
        self.assertEqual((r["updated"], r["repo"], r["pr"], r["head"], r["comment_action"]), (True, "o/r", 1, H12, "created"))
        made = fake.comments[r["comment"]]["body"]
        self.assertTrue(made.startswith(f"<!-- explain-diff-html:comment o/r#1 head={H12} -->"))
        self.assertIn("### Background", made)
        self.assertEqual(fake.body, CONCISE)
        self.assertNotIn("NOTE:", out)

    def test_updates_our_existing_comment_in_place(self):
        fake = FakeGH(body=CONCISE, comments=[human(10, "LGTM", "2026-10-01T00:00:00Z"), comment(11, cur(), "2026-10-02T00:00:00Z")])
        code, out, _ = self.run_script(fake)
        r = self.receipt(out)
        self.assertEqual((code, r["comment"], r["comment_action"]), (0, 11, "updated"))
        self.assertIn(f"head={H12}", fake.comments[11]["body"])
        self.assertEqual(fake.comments[10]["body"], "LGTM")
        self.assertEqual(len(fake.comments), 2)

    def test_pr_author_owns_a_user_account_comment(self):
        fake = FakeGH(body=CONCISE, author="nv-slang-bot",
                      comments=[comment(12, cur(), "2026-10-02T00:00:00Z", login="nv-slang-bot", kind="User")])
        code, out, _ = self.run_script(fake)
        self.assertEqual((code, self.receipt(out)["comment"]), (0, 12))

    def test_self_login_owns_a_comment_on_someone_elses_pr(self):
        fake = FakeGH(body=CONCISE, author="contributor", me="nv-slang-bot",
                      comments=[comment(13, cur(), "2026-10-02T00:00:00Z", login="nv-slang-bot", kind="User")])
        code, out, _ = self.run_script(fake)
        self.assertEqual((code, self.receipt(out)["comment"]), (0, 13))

    def test_converts_our_legacy_comment_instead_of_adding_one(self):
        legacy = "<!-- explain-diff-html o/r#1 -->\n_The explanation of this PR now lives in the PR description, updated on every push._"
        fake = FakeGH(body=CONCISE, comments=[comment(20, legacy, "2026-09-20T00:00:00Z")])
        code, out, _ = self.run_script(fake)
        r = self.receipt(out)
        self.assertEqual((code, r["comment"], r["comment_action"]), (0, 20, "updated"))
        self.assertTrue(fake.comments[20]["body"].startswith("<!-- explain-diff-html:comment o/r#1 "))
        self.assertEqual(len(fake.comments), 1)

    def test_our_duplicates_collapse_to_the_oldest(self):
        fake = FakeGH(body=CONCISE, comments=[comment(31, cur("111111111111", text="b"), "2026-10-02T00:00:00Z"),
                                              comment(30, cur(text="a"), "2026-10-01T00:00:00Z")])
        code, out, _ = self.run_script(fake)
        r = self.receipt(out)
        self.assertEqual((code, r["comment"], r["pointers"]), (0, 30, [31]))
        self.assertTrue(fake.comments[31]["body"].startswith("<!-- explain-diff-html:pointer o/r#1 -->"))
        self.assertIn("issuecomment-30", fake.comments[31]["body"])
        fake.calls.clear()
        code, out, _ = self.run_script(fake)
        self.assertEqual((self.receipt(out)["comment"], self.receipt(out)["pointers"]), (30, []))
        self.assertFalse(any("comments/31" in " ".join(c) for c in fake.writes()))

    # --- ownership (codex blocker 1) -------------------------------------------

    def test_a_maintainer_comment_quoting_the_marker_is_never_touched(self):
        quote = cur(text="> annotated copy of the bot's explanation, with my notes")
        fake = FakeGH(body=CONCISE, comments=[human(40, quote, "2026-10-01T00:00:00Z")])  # editable: fail_patch is empty
        code, out, _ = self.run_script(fake)
        r = self.receipt(out)
        self.assertEqual((code, r["comment_action"]), (0, "created"))
        self.assertEqual(fake.comments[40]["body"], quote)
        self.assertFalse(any("comments/40" in " ".join(c) for c in fake.writes()))

    def test_a_marker_for_another_pr_is_never_touched(self):
        other = cur(ref="o/r#2")
        fake = FakeGH(body=CONCISE, comments=[comment(41, other, "2026-10-01T00:00:00Z")])
        code, out, _ = self.run_script(fake)
        self.assertEqual((code, self.receipt(out)["comment_action"]), (0, "created"))
        self.assertEqual(fake.comments[41]["body"], other)

    def test_marker_must_open_the_comment(self):
        mid = "Here is what the bot wrote:\n" + cur()
        fake = FakeGH(body=CONCISE, comments=[comment(42, mid, "2026-10-01T00:00:00Z")])
        code, out, _ = self.run_script(fake)
        self.assertEqual((code, self.receipt(out)["comment_action"]), (0, "created"))
        self.assertEqual(fake.comments[42]["body"], mid)

    # --- failures never print the receipt (codex should-fix 2) ------------------

    def test_failed_update_exits_5_without_receipt_or_new_comment(self):
        fake = FakeGH(body=CONCISE, comments=[comment(50, cur(), "2026-10-01T00:00:00Z")], fail_patch={50})
        code, out, err = self.run_script(fake)
        self.assertEqual(code, 5)
        self.assertFalse(self.has_receipt(out))
        self.assertIn("502", err)
        self.assertEqual(len(fake.comments), 1)  # no POST fallback

    def test_failed_duplicate_cleanup_exits_5_without_receipt(self):
        fake = FakeGH(body=CONCISE, comments=[comment(51, cur(), "2026-10-01T00:00:00Z"), comment(52, cur(), "2026-10-02T00:00:00Z")],
                      fail_patch={52})
        code, out, _ = self.run_script(fake)
        self.assertEqual(code, 5)
        self.assertFalse(self.has_receipt(out))

    def test_concurrent_create_is_collapsed_before_success(self):
        def racer(f):
            if 700 not in f.comments:
                f.comments[700] = comment(700, cur(H12, text="from a concurrent run"), "2026-10-05T00:00:01Z")
        fake = FakeGH(body=CONCISE, on_post=racer)
        code, out, _ = self.run_script(fake)
        self.assertEqual(code, 0)
        r = self.receipt(out)
        mine = [c for c in fake.comments.values() if c["body"].startswith("<!-- explain-diff-html:comment ")]
        self.assertEqual([c["id"] for c in mine], [901])  # ours is older, so it is kept
        self.assertEqual(r["comment"], 901)
        self.assertTrue(fake.comments[700]["body"].startswith("<!-- explain-diff-html:pointer o/r#1 -->"))

    def test_never_converging_exits_5(self):
        def flood(f):
            for i in range(800, 803):
                f.comments.setdefault(i, comment(i, cur(H12), f"2026-10-05T00:00:0{i - 800}Z"))
        fake = FakeGH(body=CONCISE, on_post=flood, fail_patch={801})
        code, out, _ = self.run_script(fake)
        self.assertEqual(code, 5)
        self.assertFalse(self.has_receipt(out))

    # --- the description (codex blocker 3) --------------------------------------

    def test_strips_the_old_block_from_the_top_of_the_description(self):
        fake = FakeGH(body=OLD_SECTION + "\n\nPart of #13073.\n\n" + DISCLAIMER + "\n")
        code, out, _ = self.run_script(fake)
        self.assertEqual(code, 0)
        self.assertEqual(fake.body, "Part of #13073.\n\n" + DISCLAIMER + "\n")
        self.assertEqual(self.receipt(out)["description"], "stripped")

    def test_end_literal_inside_the_explanation_still_strips_the_whole_block(self):
        body = ("<!-- explain-diff-html:start o/r#1 head=000000000000 -->\n\n## 📖 Explanation\n\n```\n" + U.END +
                "\n```\nmore walkthrough\n\n" + U.END + "\n\nFixes #1\n")
        fake = FakeGH(body=body)
        code, _out, _ = self.run_script(fake)
        self.assertEqual(code, 0)
        self.assertEqual(fake.body, "Fixes #1\n")

    def test_authored_marker_example_is_left_alone(self):
        body = CONCISE + "\nExample of the old wrapper:\n```\n<!-- explain-diff-html:start o/r#1 head=000000000000 -->\n...\n" + U.END + "\n```\n"
        fake = FakeGH(body=body)
        code, out, _ = self.run_script(fake)
        self.assertEqual(code, 0)
        self.assertEqual(fake.body, body)
        self.assertIn("will not remove", out)
        self.assertTrue(self.receipt(out)["description"].startswith("left: an explain-diff start marker that is not at the top"))

    def test_unmatched_start_is_left_alone(self):
        body = "<!-- explain-diff-html:start o/r#1 head=000000000000 -->\n\nhalf an explanation and then the author's text\n"
        fake = FakeGH(body=body)
        code, out, _ = self.run_script(fake)
        self.assertEqual(code, 0)
        self.assertEqual(fake.body, body)
        self.assertIn("no end marker", out)

    def test_ambiguous_ends_with_text_after_are_left_alone(self):
        body = ("<!-- explain-diff-html:start o/r#1 head=000000000000 -->\n\nx\n" + U.END + "\n\nAuthor note that quotes " + U.END + "\nand more text\n")
        fake = FakeGH(body=body)
        _code, out, _ = self.run_script(fake)
        self.assertEqual(fake.body, body)
        self.assertIn("several end markers", out)

    def test_block_for_another_pr_is_left_alone(self):
        body = OLD_SECTION.replace("o/r#1", "o/r#9") + "\n\nFixes #9\n"
        fake = FakeGH(body=body)
        _code, out, _ = self.run_script(fake)
        self.assertEqual(fake.body, body)
        self.assertIn("o/r#9", out)

    def test_short_description_gets_a_note_but_still_succeeds(self):
        fake = FakeGH(body=OLD_SECTION + "\n\nFixes #1\n")
        code, out, _ = self.run_script(fake)
        self.assertEqual(code, 0)
        note = [line for line in out.splitlines() if line.startswith("NOTE:")]
        self.assertEqual(len(note), 1)
        self.assertIn("gh pr edit 1 -R o/r --body-file", note[0])
        self.assertTrue(self.receipt(out)["updated"])

    # --- guards -------------------------------------------------------------------

    def test_refuses_an_oversized_explanation(self):
        fake = FakeGH(body=CONCISE)
        code, _out, err = self.run_script(fake, explanation="x" * (U.MAX_COMMENT + 1))
        self.assertEqual(code, 3)
        self.assertIn("over", err)
        self.assertEqual(fake.writes(), [])

    def test_head_mismatch_writes_nothing(self):
        fake = FakeGH(body=CONCISE, live="f" * 40)
        code, _, err = self.run_script(fake)
        self.assertEqual(code, 4)
        self.assertIn("head mismatch", err)
        self.assertEqual(fake.writes(), [])

    def test_dry_run_writes_nothing(self):
        fake = FakeGH(body=OLD_SECTION, comments=[comment(60, cur(), "2026-10-01T00:00:00Z")])
        code, _out, err = self.run_script(fake, extra=["--dry-run"])
        self.assertEqual(code, 0)
        self.assertIn("[dry-run]", err)
        self.assertIn('"update 60"', err)
        self.assertIn('"stripped"', err)
        self.assertEqual(fake.writes(), [])


class QuizPositions(unittest.TestCase):
    def test_spread_out_and_deterministic(self):
        for sha in ["0" * 40, "f" * 40, "84be79e6068bccc4562d791493727f27b009bc3b", "deadbeef"]:
            picks = U.quiz_positions(sha)
            self.assertEqual(len(picks), 5)
            self.assertGreaterEqual(len(set(picks)), 3, picks)
            self.assertLessEqual(max(picks.count(c) for c in picks), 2, picks)
            self.assertEqual(U.quiz_positions(sha), picks)

    def test_not_always_a_across_many_heads(self):
        firsts = {U.quiz_positions(f"{i:040x}")[0] for i in range(50)}
        self.assertGreater(len(firsts), 1)

    def test_three_option_compact_quiz(self):
        picks = U.quiz_positions("abc1234", questions=3, options=3)
        self.assertEqual(sorted(picks), ["A", "B", "C"])


